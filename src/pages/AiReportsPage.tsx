import React, { useState } from 'react';
import {
  AlertCircle,
  CheckCircle2,
  Download,
  FileText,
  Printer,
  ShieldAlert,
  Sparkles,
} from 'lucide-react';
import { useAuth } from '../contexts/AuthContext';
import { formatFirestoreError } from '../lib/inventoryUtils';
import {
  AiUnavailableError,
  generateAiInventoryReport,
  type OperationalDatasetInput,
} from '../services/apiService';
import { saveAiReport } from '../services/firestoreService';
import { AiReport, AnonymizedOperationalSnapshot } from '../types/bloodBank';

interface AiReportsPageProps {
  reports: AiReport[];
  liveDataset?: OperationalDatasetInput;
}

export function AiReportsPage({ reports, liveDataset }: AiReportsPageProps) {
  const { userProfile } = useAuth();
  const [selectedReport, setSelectedReport] = useState<AiReport | null>(null);
  const [fallbackSnapshot, setFallbackSnapshot] =
    useState<AnonymizedOperationalSnapshot | null>(null);
  const [generating, setGenerating] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);
  const [successMsg, setSuccessMsg] = useState<string | null>(null);

  const activeReport = selectedReport ?? reports[0] ?? null;

  const handleGenerateReport = async () => {
    if (!userProfile) return;
    setGenerating(true);
    setErrorMsg(null);
    setSuccessMsg(null);
    setFallbackSnapshot(null);
    try {
      const res = await generateAiInventoryReport(liveDataset);
      const newId = await saveAiReport(res.report, userProfile);
      setSuccessMsg(
        'Generated and archived new Gemini AI inventory report in Firestore.'
      );
      setSelectedReport({
        id: newId,
        ...res.report,
        generatedBy: userProfile.uid,
        generatedByName: userProfile.displayName,
        createdAt: new Date().toISOString(),
      });
    } catch (err) {
      if (err instanceof AiUnavailableError) {
        setErrorMsg(err.message);
        setFallbackSnapshot(err.deterministicSummary);
      } else {
        setErrorMsg(formatFirestoreError(err));
      }
    } finally {
      setGenerating(false);
    }
  };

  const handleDownloadReport = (report: AiReport) => {
    const content = [
      report.title,
      `Generated By: ${report.generatedByName}`,
      `Generated At: ${report.createdAt || new Date().toISOString()}`,
      `Total Available Units: ${report.totalAvailableUnits}`,
      `Near-Expiry Units: ${report.nearExpiryUnits}`,
      `Expired Units: ${report.expiredUnits}`,
      `Quarantined Units: ${report.quarantinedUnits}`,
      `Low-Stock Groups: ${report.lowStockGroups.join(', ') || 'None'}`,
      `Illustrative Thresholds: Low <= ${report.lowStockMaxThreshold}, Moderate <= ${report.moderateStockMaxThreshold}`,
      '',
      '--- REPORT SUMMARY ---',
      report.summaryText,
      '',
      '--- SUGGESTED ADMINISTRATIVE ACTIONS ---',
      ...report.recommendations.map((r, i) => `${i + 1}. ${r}`),
      '',
      `DISCLAIMER: ${report.safetyDisclaimer}`,
    ].join('\n');

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${report.title.toLowerCase().replace(/[^a-z0-9]+/g, '_')}.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadDeterministicFallback = (
    snap: AnonymizedOperationalSnapshot
  ) => {
    const lines = [
      `Deterministic Inventory Summary (Non-AI Fallback) — ${snap.generatedAt.slice(0, 10)}`,
      `Source: Direct Firestore Aggregation (Gemini AI unavailable)`,
      `Total Available Units: ${snap.totalAvailableUnits}`,
      `Near-Expiry Units: ${snap.nearExpiryUnits}`,
      `Expired Units: ${snap.expiredUnits}`,
      `Quarantined Units: ${snap.quarantinedUnits}`,
      `Low-Stock Groups (<= ${snap.thresholds.lowStockMax}): ${snap.lowStockGroups.join(', ') || 'None'}`,
      '',
      '--- BLOOD GROUP BREAKDOWN ---',
      ...snap.byBloodGroup.map(
        (g) =>
          `${g.bloodGroup}: ${g.availableUnits} available | ${g.nearExpiryUnits} near-expiry | ${g.pendingRequestedUnits} pending req | status=${g.status}`
      ),
    ].join('\n');

    const blob = new Blob([lines], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `deterministic_inventory_summary_${snap.generatedAt.slice(0, 10)}.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 no-print">
        <div>
          <h2 className="font-display text-xl font-bold text-slate-900">
            AI Inventory Reports
          </h2>
          <p className="text-sm text-slate-500 mt-0.5">
            Administrative reports synthesized from live anonymized Firestore stock metrics via Firebase AI Logic (Gemini free tier).
          </p>
        </div>

        <button
          type="button"
          disabled={generating}
          onClick={handleGenerateReport}
          className="inline-flex items-center gap-2 px-4 py-2.5 text-sm font-semibold text-white bg-red-700 hover:bg-red-800 rounded-lg transition-colors whitespace-nowrap shrink-0 disabled:opacity-60"
        >
          <Sparkles className="w-4 h-4" />
          {generating ? 'Generating Report...' : 'Generate AI Inventory Report'}
        </button>
      </div>

      {errorMsg && (
        <div className="p-3.5 bg-red-50 border border-red-200 rounded-lg flex items-start gap-2 text-xs text-red-800 no-print">
          <AlertCircle className="w-4 h-4 shrink-0 mt-0.5" />
          <div>
            <div className="font-semibold">Gemini AI Report Generation Unavailable</div>
            <p className="mt-0.5">{errorMsg}</p>
          </div>
        </div>
      )}
      {successMsg && (
        <div className="p-3.5 bg-emerald-50 border border-emerald-200 rounded-lg flex items-start gap-2 text-xs text-emerald-800 no-print">
          <CheckCircle2 className="w-4 h-4 shrink-0 mt-0.5" />
          <span>{successMsg}</span>
        </div>
      )}

      {fallbackSnapshot && (
        <div className="bg-white border border-amber-200 rounded-xl p-5 space-y-4 no-print">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-slate-100 pb-3">
            <div>
              <h3 className="font-display text-sm font-bold text-slate-900">
                Deterministic Inventory Summary (Non-AI Fallback)
              </h3>
              <p className="text-xs text-slate-500">
                Computed directly from Firestore while Gemini AI is unavailable — not archived as an AI report.
              </p>
            </div>
            <button
              type="button"
              onClick={() => handleDownloadDeterministicFallback(fallbackSnapshot)}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 rounded-lg shrink-0"
            >
              <Download className="w-3.5 h-3.5" />
              Export Deterministic TXT
            </button>
          </div>
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs">
            <div className="p-2.5 bg-slate-50 border border-slate-200 rounded-lg">
              <div className="text-slate-500">Available</div>
              <div className="font-mono font-bold text-slate-900 text-base">
                {fallbackSnapshot.totalAvailableUnits}
              </div>
            </div>
            <div className="p-2.5 bg-slate-50 border border-slate-200 rounded-lg">
              <div className="text-slate-500">Near-Expiry</div>
              <div className="font-mono font-bold text-amber-700 text-base">
                {fallbackSnapshot.nearExpiryUnits}
              </div>
            </div>
            <div className="p-2.5 bg-slate-50 border border-slate-200 rounded-lg">
              <div className="text-slate-500">Expired</div>
              <div className="font-mono font-bold text-red-700 text-base">
                {fallbackSnapshot.expiredUnits}
              </div>
            </div>
            <div className="p-2.5 bg-slate-50 border border-slate-200 rounded-lg">
              <div className="text-slate-500">Low Groups</div>
              <div className="font-mono font-bold text-red-700 text-sm mt-0.5">
                {fallbackSnapshot.lowStockGroups.join(', ') || 'None'}
              </div>
            </div>
          </div>
        </div>
      )}

      <div className="grid lg:grid-cols-12 gap-6 items-start">
        {/* Archived Reports List */}
        <div className="lg:col-span-4 bg-white border border-slate-200 rounded-xl overflow-hidden no-print">
          <div className="px-4 py-3.5 border-b border-slate-200 font-display text-sm font-semibold text-slate-900">
            Saved Reports ({reports.length})
          </div>
          {reports.length === 0 ? (
            <div className="p-6 text-center text-xs text-slate-500">
              No AI reports archived yet.
            </div>
          ) : (
            <div className="divide-y divide-slate-100 max-h-[540px] overflow-y-auto">
              {reports.map((rep) => {
                const isSelected = activeReport?.id === rep.id;
                return (
                  <button
                    key={rep.id}
                    type="button"
                    onClick={() => setSelectedReport(rep)}
                    className={`w-full text-left px-4 py-3.5 transition-colors ${
                      isSelected ? 'bg-red-50/70' : 'hover:bg-slate-50'
                    }`}
                  >
                    <div className="text-sm font-semibold text-slate-900 line-clamp-1">
                      {rep.title}
                    </div>
                    <div className="text-xs text-slate-500 mt-1 font-mono tabular-nums">
                      {rep.totalAvailableUnits} units · {rep.lowStockGroups.length}{' '}
                      low groups
                    </div>
                    <div className="text-[11px] text-slate-400 mt-0.5">
                      {rep.generatedByName} ·{' '}
                      {rep.createdAt ? rep.createdAt.slice(0, 10) : 'Today'}
                    </div>
                  </button>
                );
              })}
            </div>
          )}
        </div>

        {/* Selected Report Document View */}
        <div className="lg:col-span-8 bg-white border border-slate-200 rounded-xl p-6 sm:p-8 space-y-6">
          {!activeReport ? (
            <div className="py-12 text-center space-y-2">
              <FileText className="w-8 h-8 text-slate-300 mx-auto" />
              <p className="text-sm text-slate-500">
                Select an archived report or generate a new AI inventory report.
              </p>
            </div>
          ) : (
            <>
              <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-4 border-b border-slate-200 pb-4">
                <div>
                  <div className="text-xs font-mono text-slate-500">
                    {activeReport.createdAt
                      ? activeReport.createdAt.slice(0, 19).replace('T', ' ')
                      : 'Just now'}{' '}
                    · Prepared for {activeReport.generatedByName}
                  </div>
                  <h3 className="font-display text-lg font-bold text-slate-900 mt-1">
                    {activeReport.title}
                  </h3>
                </div>
                <div className="flex items-center gap-2 no-print shrink-0">
                  <button
                    type="button"
                    onClick={() => handleDownloadReport(activeReport)}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 rounded-lg"
                  >
                    <Download className="w-3.5 h-3.5" />
                    Export TXT
                  </button>
                  <button
                    type="button"
                    onClick={() => window.print()}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 rounded-lg"
                  >
                    <Printer className="w-3.5 h-3.5" />
                    Print
                  </button>
                </div>
              </div>

              <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
                <div className="p-3 bg-slate-50 border border-slate-200 rounded-lg">
                  <div className="text-[11px] text-slate-500">Available Units</div>
                  <div className="font-mono tabular-nums text-lg font-bold text-slate-900">
                    {activeReport.totalAvailableUnits}
                  </div>
                </div>
                <div className="p-3 bg-slate-50 border border-slate-200 rounded-lg">
                  <div className="text-[11px] text-slate-500">Near-Expiry</div>
                  <div className="font-mono tabular-nums text-lg font-bold text-amber-700">
                    {activeReport.nearExpiryUnits}
                  </div>
                </div>
                <div className="p-3 bg-slate-50 border border-slate-200 rounded-lg">
                  <div className="text-[11px] text-slate-500">Expired</div>
                  <div className="font-mono tabular-nums text-lg font-bold text-red-700">
                    {activeReport.expiredUnits}
                  </div>
                </div>
                <div className="p-3 bg-slate-50 border border-slate-200 rounded-lg">
                  <div className="text-[11px] text-slate-500">Quarantined</div>
                  <div className="font-mono tabular-nums text-lg font-bold text-slate-700">
                    {activeReport.quarantinedUnits}
                  </div>
                </div>
              </div>

              <div className="text-xs text-slate-600">
                <strong>
                  Low-Stock Groups (&le; {activeReport.lowStockMaxThreshold} units):
                </strong>{' '}
                <span className="font-mono">
                  {activeReport.lowStockGroups.length > 0
                    ? activeReport.lowStockGroups.join(', ')
                    : 'None'}
                </span>
              </div>

              <div className="space-y-3 text-sm text-slate-700 leading-relaxed whitespace-pre-line">
                {activeReport.summaryText}
              </div>

              {activeReport.recommendations.length > 0 && (
                <div className="space-y-2 pt-3 border-t border-slate-100">
                  <h4 className="text-xs font-semibold text-slate-800">
                    Suggested Management Actions
                  </h4>
                  <ul className="list-disc pl-5 space-y-1 text-sm text-slate-700">
                    {activeReport.recommendations.map((rec, idx) => (
                      <li key={idx}>{rec}</li>
                    ))}
                  </ul>
                </div>
              )}

              <div className="p-3.5 bg-amber-50/70 border border-amber-200 rounded-lg flex items-start gap-2.5 text-xs text-amber-900">
                <ShieldAlert className="w-4 h-4 shrink-0 mt-0.5 text-amber-700" />
                <span>{activeReport.safetyDisclaimer}</span>
              </div>
            </>
          )}
        </div>
      </div>
    </div>
  );
}
